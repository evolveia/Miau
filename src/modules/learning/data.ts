function createPastelVisualSvgUrl(
  emoji: string,
  badge: string,
  bgStart = '#f5edff',
  bgEnd = '#e4d4ff',
  ringColor = '#9b72cf'
): string {
  const safeBadge = badge.replace(/[<>&"']/g, '');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0%" stop-color="${bgStart}"/><stop offset="100%" stop-color="${bgEnd}"/></linearGradient></defs><rect width="120" height="120" rx="28" fill="url(#g)" stroke="${ringColor}" stroke-width="3"/><circle cx="60" cy="52" r="34" fill="#ffffff" fill-opacity="0.72"/><text x="60" y="64" font-size="42" text-anchor="middle">${emoji}</text><rect x="20" y="90" width="80" height="20" rx="10" fill="${ringColor}"/><text x="60" y="104" font-family="sans-serif" font-size="11" font-weight="bold" fill="#ffffff" text-anchor="middle">${safeBadge}</text></svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

